export function t(key) {
  return i18n[state.currentLang][key] || key;
}

export function updateTranslations() {
  // Translate text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (i18n[state.currentLang][key]) {
      el.textContent = i18n[state.currentLang][key];
    }
  });

  // Translate title/tooltip attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    if (i18n[state.currentLang][key]) {
      el.title = i18n[state.currentLang][key];
    }
  });

  // Translate placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (i18n[state.currentLang][key]) {
      el.placeholder = i18n[state.currentLang][key];
    }
  });
}

export function initLanguage() {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => {
      state.currentLang = btn.dataset.lang;
      document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
      btn.classList.add('active');
      updateTranslations();
    });
  });

  // Apply translations on initial load
  updateTranslations();
}
